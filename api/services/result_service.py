"""Read existing pipeline artifacts for the frontend-facing API."""

import json
import re
from pathlib import Path
from typing import Any

from fastapi import HTTPException

from run import OUTPUT_DIR


RUN_ID_PATTERN = re.compile(r"^[a-f0-9]{32}$")
ARTIFACTS = {
    "clauses_json": ("_m2_output.json", "application/json"),
    "annotations_csv": ("_m2_annotations.csv", "text/csv"),
    "compliance_report": ("_m3_compliance_report.json", "application/json"),
    "updated_contract_txt": ("_updated_contract.txt", "text/plain"),
    "updated_contract_pdf": ("_updated_contract.pdf", "application/pdf"),
}


def run_links(run_id: str) -> dict[str, str]:
    """Build stable relative URLs without accepting a client filesystem path."""
    return {
        "self": f"/api/v1/runs/{run_id}",
        "clauses": f"/api/v1/runs/{run_id}/clauses",
        "report": f"/api/v1/runs/{run_id}/report",
    }


def _output_directory() -> Path:
    return Path(OUTPUT_DIR).resolve()


def _validate_run_id(run_id: str) -> None:
    if not RUN_ID_PATTERN.fullmatch(run_id):
        raise HTTPException(status_code=404, detail="Run not found.")


def _validate_artifact_type(artifact_type: str) -> None:
    if artifact_type not in ARTIFACTS:
        raise HTTPException(status_code=400, detail="Invalid artifact type.")


def _resolve_base_name(run_id: str) -> str:
    """Locate a run using only the UUID generated by the API upload service."""
    _validate_run_id(run_id)
    output_directory = _output_directory()
    if not output_directory.is_dir():
        raise HTTPException(status_code=404, detail="Run not found.")

    marker = f"_{run_id}_m2_output.json"
    matches = [
        path
        for path in output_directory.iterdir()
        if path.is_file() and path.name.endswith(marker)
    ]
    if len(matches) != 1:
        raise HTTPException(status_code=404, detail="Run not found.")

    return matches[0].name[: -len("_m2_output.json")]


def get_artifact_path(run_id: str, artifact_type: str) -> Path:
    """Resolve one approved artifact and ensure it remains within OUTPUT_DIR."""
    _validate_artifact_type(artifact_type)
    base_name = _resolve_base_name(run_id)
    suffix, _ = ARTIFACTS[artifact_type]
    output_directory = _output_directory()
    artifact_path = (output_directory / f"{base_name}{suffix}").resolve()

    if artifact_path.parent != output_directory or not artifact_path.is_file():
        raise HTTPException(status_code=404, detail="Artifact not found.")

    return artifact_path


def get_uploaded_filename(run_id: str) -> str:
    """Return the generated upload filename associated with an existing run."""
    return f"{_resolve_base_name(run_id)}.pdf"


def _read_json_artifact(run_id: str, artifact_type: str) -> Any:
    path = get_artifact_path(run_id, artifact_type)
    try:
        with path.open("r", encoding="utf-8") as artifact_file:
            return json.load(artifact_file)
    except json.JSONDecodeError as exc:
        raise HTTPException(status_code=500, detail="Generated artifact is invalid JSON.") from exc


def get_clauses(run_id: str) -> list[dict[str, Any]]:
    """Return the unmodified milestone-2 clause/risk objects."""
    clauses = _read_json_artifact(run_id, "clauses_json")
    if not isinstance(clauses, list) or not all(isinstance(clause, dict) for clause in clauses):
        raise HTTPException(status_code=500, detail="Generated clause artifact has an invalid structure.")
    return clauses


def get_report(run_id: str) -> dict[str, Any]:
    """Return the unmodified milestone-3 report object."""
    report = _read_json_artifact(run_id, "compliance_report")
    if not isinstance(report, dict):
        raise HTTPException(status_code=500, detail="Generated report artifact has an invalid structure.")
    return report


def get_summary(run_id: str) -> dict[str, int]:
    """Calculate display counts from existing clause and report artifacts."""
    clauses = get_clauses(run_id)
    report = get_report(run_id)
    counts = {"high_risk": 0, "medium_risk": 0, "low_risk": 0}

    for clause in clauses:
        risk = clause.get("risk", {})
        severity = risk.get("severity", "") if isinstance(risk, dict) else ""
        severity = severity.lower() if isinstance(severity, str) else ""
        if severity == "high":
            counts["high_risk"] += 1
        elif severity == "medium":
            counts["medium_risk"] += 1
        else:
            counts["low_risk"] += 1

    compliance_report = report.get("compliance_report", {})
    total_issues = compliance_report.get("total_issues_detected", 0)
    return {
        "total_clauses": len(clauses),
        **counts,
        "total_issues": total_issues if isinstance(total_issues, int) else 0,
    }


def get_artifact_metadata(run_id: str) -> list[dict[str, str]]:
    """Return only existing allow-listed files for a completed run."""
    base_name = _resolve_base_name(run_id)
    metadata = []
    for artifact_type, (suffix, _) in ARTIFACTS.items():
        path = get_artifact_path(run_id, artifact_type)
        metadata.append(
            {
                "type": artifact_type,
                "filename": f"{base_name}{suffix}",
                "download_url": f"/api/v1/runs/{run_id}/artifacts/{artifact_type}",
            }
        )
    return metadata


def artifact_media_type(artifact_type: str) -> str:
    """Return the media type for one already-validated artifact type."""
    _validate_artifact_type(artifact_type)
    return ARTIFACTS[artifact_type][1]
